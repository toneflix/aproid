"""Builds every app icon and logo asset from flyylink-logo.svg.

Needs Python 3 with Pillow, and Node with Playwright (used to rasterise the SVGs).
Run from the repo root: python3 branding/generate.py
"""
import json
import subprocess
import tempfile
from io import BytesIO
from pathlib import Path

from PIL import Image

from mark import Mark

ROOT = Path(__file__).resolve().parent.parent
BRANDING = ROOT / "branding"
RES = ROOT / "android/app/src/main/res"
MAC = ROOT / "macos"
WINDOWS = ROOT / "windows/src/FlyyLink"

TILE_TOP = "#F6C101"
TILE_BOTTOM = "#BB8C01"


class Rasterizer:
    """Renders SVG strings to PNG bytes with headless Chromium."""

    SCRIPT = """
const { chromium } = require('playwright');
(async () => {
  const jobs = JSON.parse(require('fs').readFileSync(process.argv[2], 'utf8'));
  const browser = await chromium.launch();
  for (const job of jobs) {
    const page = await browser.newPage({ viewport: { width: job.size, height: job.size } });
    await page.setContent(`<body style="margin:0">${job.svg}</body>`);
    await page.screenshot({ path: job.out, omitBackground: true });
    await page.close();
  }
  await browser.close();
})();
"""

    def render(self, jobs):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            script = tmp / "render.js"
            spec = tmp / "jobs.json"
            outs = [tmp / f"{i}.png" for i in range(len(jobs))]

            script.write_text(self.SCRIPT)
            spec.write_text(json.dumps([{"svg": svg, "size": size, "out": str(out)} for (svg, size), out in zip(jobs, outs)]))
            subprocess.run(["node", str(script), str(spec)], check=True)

            return [Image.open(BytesIO(out.read_bytes())).convert("RGBA") for out in outs]


class Brand:
    def __init__(self, mark: Mark):
        self.mark = mark

    def _gradient_points(self, scale, dx, dy):
        (x0, y0), (x1, y1) = self.mark.gradient

        return x0 * scale + dx, y0 * scale + dy, x1 * scale + dx, y1 * scale + dy

    def logo_svg(self, size=100):
        x1, y1, x2, y2 = self._gradient_points(size, 0, 0)
        a, b = self.mark.stops

        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">'
            f'<defs><linearGradient id="mark" gradientUnits="userSpaceOnUse" x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}">'
            f'<stop offset="0" stop-color="{a}"/><stop offset="1" stop-color="{b}"/></linearGradient></defs>'
            f'<path fill="url(#mark)" d="{self.mark.path_data(size)}"/></svg>'
        )

    def tile_svg(self, rounded=True):
        """The 1024px app icon: the mark on a gold tile, following the macOS icon grid when rounded."""
        side = 600
        offset = 512 - side / 2
        x1, y1, x2, y2 = self._gradient_points(side, offset, offset)
        a, b = self.mark.stops
        tile = (
            '<rect x="100" y="112" width="824" height="824" rx="185" fill="#000" opacity="0.35" filter="url(#shadow)"/>'
            '<rect x="100" y="100" width="824" height="824" rx="185" fill="url(#tile)"/>'
            if rounded
            else '<rect width="1024" height="1024" fill="url(#tile)"/>'
        )

        return (
            '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><defs>'
            '<filter id="shadow" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="14"/></filter>'
            f'<linearGradient id="tile" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{TILE_TOP}"/><stop offset="1" stop-color="{TILE_BOTTOM}"/></linearGradient>'
            f'<linearGradient id="mark" gradientUnits="userSpaceOnUse" x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}">'
            f'<stop offset="0" stop-color="{a}"/><stop offset="1" stop-color="{b}"/></linearGradient></defs>'
            f'{tile}<path fill="url(#mark)" d="{self.mark.path_data(side, offset, offset)}"/></svg>'
        )

    def vector(self, viewport, side, fill=None, size_dp=None):
        """An Android vector drawable of the mark, with the logo gradient unless a flat fill is given."""
        offset = (viewport - side) / 2
        size_dp = size_dp or viewport
        head = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by branding/generate.py from branding/flyylink-logo.svg. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        )
        data = self.mark.path_data(side, offset, offset)

        if fill:
            return head + f'    <path\n        android:fillColor="{fill}"\n        android:pathData="{data}" />\n</vector>\n'

        x1, y1, x2, y2 = self._gradient_points(side, offset, offset)
        a, b = (c.upper().replace("#", "#FF") for c in self.mark.stops)

        return head + (
            f'    <path android:pathData="{data}">\n'
            '        <aapt:attr name="android:fillColor">\n'
            f'            <gradient\n                android:type="linear"\n'
            f'                android:startX="{x1:.2f}"\n                android:startY="{y1:.2f}"\n'
            f'                android:endX="{x2:.2f}"\n                android:endY="{y2:.2f}">\n'
            f'                <item android:offset="0" android:color="{a}" />\n'
            f'                <item android:offset="1" android:color="{b}" />\n'
            '            </gradient>\n        </aapt:attr>\n    </path>\n</vector>\n'
        )

    def launcher_background(self):
        top, bottom = (c.replace("#", "#FF") for c in (TILE_TOP, TILE_BOTTOM))

        return (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by branding/generate.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            '    <path android:pathData="M0,0h108v108h-108z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient\n                android:type="linear"\n'
            '                android:startX="54"\n                android:startY="0"\n'
            '                android:endX="54"\n                android:endY="108">\n'
            f'                <item android:offset="0" android:color="{top}" />\n'
            f'                <item android:offset="1" android:color="{bottom}" />\n'
            '            </gradient>\n        </aapt:attr>\n    </path>\n</vector>\n'
        )

    def csharp(self):
        x1, y1, x2, y2 = self._gradient_points(100, 0, 0)
        a, b = (c.lstrip("#").upper() for c in self.mark.stops)

        return f"""// Generated by branding/generate.py from branding/flyylink-logo.svg.
namespace FlyyLink.Icons;

/// The FlyyLink logo mark, centred in a 100 by 100 square.
public static class FlyyLinkMark
{{
    public const string Data = "{self.mark.path_data(100)}";

    /// The logo's cyan gradient, from start to end, in the same 100 by 100 square.
    public const double StartX = {x1:.3f}, StartY = {y1:.3f}, EndX = {x2:.3f}, EndY = {y2:.3f};

    public const uint StartColor = 0xFF{a}, EndColor = 0xFF{b};

    /// The gold background of the app icon, from top to bottom.
    public const uint TileTop = 0xFF{TILE_TOP.lstrip("#")}, TileBottom = 0xFF{TILE_BOTTOM.lstrip("#")};
}}
"""

    def swift(self):
        def point(p):
            return f"CGPoint(x: {p[0]:.5f}, y: {p[1]:.5f})"

        lines = []
        for op, pts in self.mark.commands:
            if op == "M":
                lines.append(f"        path.move(to: at({point(pts[0])}))")
            elif op == "L":
                lines.append(f"        path.addLine(to: at({point(pts[0])}))")
            elif op == "C":
                lines.append(
                    f"        path.addCurve(to: at({point(pts[2])}), control1: at({point(pts[0])}), control2: at({point(pts[1])}))"
                )
            else:
                lines.append("        path.closeSubpath()")

        (x0, y0), (x1, y1) = self.mark.gradient
        a, b = (c.lstrip("#").upper() for c in self.mark.stops)
        body = "\n".join(lines)

        return f"""// Generated by branding/generate.py from branding/flyylink-logo.svg.
import SwiftUI

/// The FlyyLink logo mark, centred in a square frame.
struct FlyyLinkMark: Shape {{
    /// Width of the mark relative to its height.
    static let aspect: CGFloat = {self.mark.width:.5f}

    /// The logo's cyan gradient, laid out for a square frame.
    static let gradient = LinearGradient(
        colors: [Color(hex: 0x{a}), Color(hex: 0x{b})],
        startPoint: UnitPoint(x: {x0:.5f}, y: {y0:.5f}),
        endPoint: UnitPoint(x: {x1:.5f}, y: {y1:.5f})
    )

    /// The gold background of the app icon.
    static let tile = LinearGradient(
        colors: [Color(hex: 0x{TILE_TOP.lstrip("#")}), Color(hex: 0x{TILE_BOTTOM.lstrip("#")})],
        startPoint: .top,
        endPoint: .bottom
    )

    func path(in rect: CGRect) -> Path {{
        let side = min(rect.width, rect.height)
        let origin = CGPoint(x: rect.midX - side / 2, y: rect.midY - side / 2)
        let at = {{ (p: CGPoint) in CGPoint(x: origin.x + p.x * side, y: origin.y + p.y * side) }}
        var path = Path()

{body}

        return path
    }}
}}

private extension Color {{
    init(hex: UInt32) {{
        self.init(
            red: Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue: Double(hex & 0xFF) / 255
        )
    }}
}}
"""


def main():
    brand = Brand(Mark(BRANDING / "flyylink-logo.svg"))
    rasterizer = Rasterizer()

    (BRANDING / "flyylink-mark.svg").write_text(brand.logo_svg() + "\n")
    (BRANDING / "app-icon.svg").write_text(brand.tile_svg() + "\n")

    mac_icon, play_icon, mark = rasterizer.render([(brand.tile_svg(), 1024), (brand.tile_svg(rounded=False), 1024), (brand.logo_svg(256), 256)])
    mac_icon.save(MAC / "Bundle/AppIcon.icns", sizes=[(16, 16), (32, 32), (64, 64), (128, 128), (256, 256), (512, 512), (1024, 1024)])
    play_icon.convert("RGB").resize((512, 512), Image.LANCZOS).save(BRANDING / "play-store-icon.png")

    (MAC / "Sources/FlyyLink/FlyyLinkMark.swift").write_text(brand.swift())

    windows_icon = mac_icon.crop((100, 100, 924, 924))
    windows_icon.save(WINDOWS / "Assets/FlyyLink.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    windows_icon.resize((256, 256), Image.LANCZOS).save(WINDOWS / "Assets/FlyyLink.png")
    mark.save(WINDOWS / "Assets/Tray.ico", sizes=[(16, 16), (20, 20), (24, 24), (32, 32), (40, 40), (48, 48), (64, 64)])
    (WINDOWS / "Icons/FlyyLinkMark.cs").write_text(brand.csharp())

    drawables = RES / "drawable"
    (drawables / "ic_launcher_foreground.xml").write_text(brand.vector(108, 50))
    (drawables / "ic_launcher_monochrome.xml").write_text(brand.vector(108, 50, fill="#FFFFFFFF"))
    (drawables / "ic_launcher_background.xml").write_text(brand.launcher_background())
    (drawables / "ic_flyylink_logo.xml").write_text(brand.vector(100, 100, size_dp=32))
    (drawables / "ic_stat_flyylink.xml").write_text(brand.vector(24, 22, fill="#FFFFFFFF"))


if __name__ == "__main__":
    main()
